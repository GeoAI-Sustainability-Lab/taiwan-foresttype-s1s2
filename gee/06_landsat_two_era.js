// ---- Landsat C2 L2 prep (rename to common bands, scale, cloud mask) ----
function maskQA(img){var q=img.select('QA_PIXEL');
  var m=q.bitwiseAnd(1<<1).eq(0).and(q.bitwiseAnd(1<<3).eq(0)).and(q.bitwiseAnd(1<<4).eq(0)).and(q.bitwiseAnd(1<<5).eq(0));
  return m;}
function ren57(img){var m=maskQA(img);
  return img.select(['SR_B1','SR_B2','SR_B3','SR_B4','SR_B5','SR_B7'],['blue','green','red','nir','swir1','swir2'])
    .multiply(0.0000275).add(-0.2).updateMask(m).copyProperties(img,['system:time_start']);}
function ren89(img){var m=maskQA(img);
  return img.select(['SR_B2','SR_B3','SR_B4','SR_B5','SR_B6','SR_B7'],['blue','green','red','nir','swir1','swir2'])
    .multiply(0.0000275).add(-0.2).updateMask(m).copyProperties(img,['system:time_start']);}
function idx(img){
  var ndvi=img.normalizedDifference(['nir','red']).rename('NDVI');
  var ndmi=img.normalizedDifference(['nir','swir1']).rename('NDMI');
  var nbr =img.normalizedDifference(['nir','swir2']).rename('NBR');
  var t=ee.Number(img.get('system:time_start'));
  var yr=ee.Date(t).difference(ee.Date('2000-01-01'),'year');
  var con=ee.Image(1).rename('constant');
  var cos=ee.Image(yr.multiply(2*Math.PI).cos()).rename('cos').toFloat();
  var sin=ee.Image(yr.multiply(2*Math.PI).sin()).rename('sin').toFloat();
  return img.addBands([ndvi,ndmi,nbr,con,cos,sin]);
}
function eraCol(y0,y1){
  var l5=ee.ImageCollection('LANDSAT/LT05/C02/T1_L2').filterDate(y0,y1).map(ren57);
  var l7=ee.ImageCollection('LANDSAT/LE07/C02/T1_L2').filterDate(y0,y1).map(ren57);
  var l8=ee.ImageCollection('LANDSAT/LC08/C02/T1_L2').filterDate(y0,y1).map(ren89);
  var l9=ee.ImageCollection('LANDSAT/LC09/C02/T1_L2').filterDate(y0,y1).map(ren89);
  return l5.merge(l7).merge(l8).merge(l9).filterBounds(pts).map(idx);
}
// harmonic mean/amp/phase per index over an era
function harmonic(col){
  var bands=['NDVI','NDMI','NBR']; var out=ee.Image(terr);
  bands.forEach(function(b){
    var c=col.select(['constant','cos','sin',b]);
    var fit=c.reduce(ee.Reducer.linearRegression(3,1)).select('coefficients').arrayProject([0]).arrayFlatten([['constant','cos','sin']]);
    var amp=fit.select('cos').hypot(fit.select('sin')).rename(b+'_amp');
    var pha=fit.select('sin').atan2(fit.select('cos')).rename(b+'_pha');
    var mean=col.select(b).mean().rename(b+'_mean');
    out=out.addBands([mean,amp,pha]);
  });
  return out;
}
function exportEra(name,y0,y1){
  var feat=harmonic(eraCol(y0,y1));
  var tab=feat.sampleRegions({collection:pts,properties:['cls','ptid'],scale:30,tileScale:4,geometries:false});
  Export.table.toDrive({collection:tab,description:'landsat_'+name,folder:'landsat_era',fileFormat:'CSV'});
}
