/**** 自含式:內嵌訓練點(免上傳 asset),訓練 RF→全島分類→1km 匯出 ****/
var taiwan = ee.Geometry.Rectangle([120.0, 21.85, 122.05, 25.35]);
var YEAR_START = '2023-01-01', YEAR_END = '2024-12-31';

// 內嵌點 → FeatureCollection (lon,lat,cls 1闊2針3竹)
var trainFc = ee.FeatureCollection(TRAIN.map(function(p){
  return ee.Feature(ee.Geometry.Point([p[0], p[1]]), {cls: p[2]});
}));

function maskS2(img){
  var scl = img.select('SCL');
  var good = scl.neq(3).and(scl.neq(8)).and(scl.neq(9)).and(scl.neq(10)).and(scl.neq(11));
  return img.updateMask(good).divide(10000).copyProperties(img,['system:time_start']);
}
function addIdxS2(b){
  return b.addBands([
    b.normalizedDifference(['B8','B4']).rename('NDVI'),
    b.normalizedDifference(['B8','B11']).rename('NDMI'),
    b.normalizedDifference(['B8','B12']).rename('NBR'),
    b.normalizedDifference(['B8','B5']).rename('reNDVI'),
    b.select('B7').divide(b.select('B5')).subtract(1).rename('CIre'),
    b.expression('2.5*(N-R)/(N+6*R-7.5*B+1)',{N:b.select('B8'),R:b.select('B4'),B:b.select('B2')}).rename('EVI')
  ]);
}
var s2 = ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED')
  .filterBounds(taiwan).filterDate(YEAR_START,YEAR_END)
  .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE',60)).map(maskS2).map(addIdxS2);
var PI=Math.PI;
function addT(img){
  var t=ee.Number(img.date().difference('2000-01-01','year'));
  var tb=ee.Image.constant(t).float().rename('t');
  return img.addBands(tb).addBands(ee.Image([
    tb.multiply(2*PI).cos().rename('cos1'),tb.multiply(2*PI).sin().rename('sin1'),
    tb.multiply(4*PI).cos().rename('cos2'),tb.multiply(4*PI).sin().rename('sin2'),
    ee.Image.constant(1).rename('const')]));
}
function harm(coll,band){
  var indep=['const','cos1','sin1','cos2','sin2'];
  var fit=coll.map(addT).select(indep.concat([band])).reduce(ee.Reducer.linearRegression(indep.length,1));
  var coef=fit.select('coefficients').arrayProject([0]).arrayFlatten([indep]);
  return ee.Image.cat([
    coll.select(band).mean().rename(band+'_mean'),
    coll.select(band).reduce(ee.Reducer.stdDev()).rename(band+'_std'),
    coef.select('cos1').hypot(coef.select('sin1')).rename(band+'_amp1'),
    coef.select('sin1').atan2(coef.select('cos1')).rename(band+'_phase1'),
    coef.select('cos2').hypot(coef.select('sin2')).rename(band+'_amp2'),
    coll.select(band).reduce(ee.Reducer.percentile([10,90])).rename([band+'_p10',band+'_p90'])
  ]);
}
var s2feat=ee.Image.cat(['NDVI','EVI','NDMI','reNDVI','CIre','NBR'].map(function(b){return harm(s2,b);}));
var s1=ee.ImageCollection('COPERNICUS/S1_GRD').filterBounds(taiwan).filterDate(YEAR_START,YEAR_END)
  .filter(ee.Filter.eq('instrumentMode','IW'))
  .filter(ee.Filter.listContains('transmitterReceiverPolarisation','VV'))
  .filter(ee.Filter.listContains('transmitterReceiverPolarisation','VH'))
  .filter(ee.Filter.eq('orbitProperties_pass','ASCENDING'))
  .map(function(img){var vv=img.select('VV'),vh=img.select('VH');
    return img.addBands([vh.subtract(vv).rename('RATIO'),vh.multiply(4).divide(vv.add(vh)).rename('RVI')])
              .copyProperties(img,['system:time_start']);});
var s1feat=ee.Image.cat(['VV','VH','RATIO','RVI'].map(function(b){return harm(s1,b);}));
var dem=ee.Image('USGS/SRTMGL1_003');
var terrain=ee.Image.cat([dem.rename('elev'),ee.Terrain.slope(dem).rename('slope'),ee.Terrain.aspect(dem).cos().rename('aspect_cos')]);
var features=ee.Image.cat([s2feat,s1feat,terrain]).toFloat();
var bands=features.bandNames();

var training=features.sampleRegions({collection:trainFc, properties:['cls'], scale:10, tileScale:4});
var rf=ee.Classifier.smileRandomForest(300).train(training,'cls',bands);
var classified=features.classify(rf).rename('foresttype').clip(taiwan);
var pred1km=classified.reduceResolution({reducer:ee.Reducer.mode(),maxPixels:1024}).reproject({crs:'EPSG:3826',scale:1000});

Map.centerObject(taiwan,7);
Map.addLayer(pred1km,{min:1,max:3,palette:['1b9e77','7570b3','d95f02']},'1km 推論 (1闊2針3竹)');
print('訓練點數', trainFc.size());

Export.image.toDrive({image:pred1km.toByte(), description:'taiwan_foresttype_1km',
  folder:'forest_lulc', region:taiwan, scale:1000, crs:'EPSG:3826', maxPixels:1e10});
